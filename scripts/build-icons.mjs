// Regenerates src/main/ts/ui/icons/imported.ts from the previous frontend's multi-colour sprite.
//   node scripts/build-icons.mjs <path to icons.svg>
// Cleaning: ids dropped (they repeat inside the sprite), `var(--colorN, #hex)` resolved to its
// fallback, path numbers rounded to one decimal, one <symbol> per icon with its own viewBox.
import { readFileSync, writeFileSync } from "node:fs";

const RENAME = { paper: "papyrus" };
const source = readFileSync(process.argv[2], "utf8");

const clean = (body) =>
  body
    .replace(/\s+id="[^"]*"/g, "")
    .replace(/var\(--color\d+,\s*(#[0-9a-fA-F]+)\)/g, "$1")
    .replace(
      / d="([^"]*)"/g,
      (_, d) =>
        ` d="${d.replace(/-?\d+\.\d+/g, (n) => {
          const r = Math.round(n * 10) / 10;
          return r === 0 ? " 0" : String(r); // a bare "0" would fuse with the number before it
        })}"`,
    )
    .replace(/\s*stroke-miterlimit="10"/g, "")
    .replace(/\s+/g, " ")
    .replace(/> </g, "><")
    .trim();

const icons = [
  ...source.matchAll(/<symbol id="([^"]+)" viewBox="([^"]+)"[^>]*>(.*?)<\/symbol>/gs),
].map(([, id, viewBox, body]) => {
  const name = id.toLowerCase();
  return [RENAME[name] ?? name, viewBox, `<g fill="none">${clean(body)}</g>`];
});
icons.sort(([a], [b]) => a.localeCompare(b));

const entries = icons
  .map(
    ([id, viewBox, body]) =>
      `  ${JSON.stringify(id)}: { viewBox: ${JSON.stringify(viewBox)}, body: ${JSON.stringify(body)} },`,
  )
  .join("\n");
writeFileSync(
  new URL("../src/main/ts/ui/icons/imported.ts", import.meta.url),
  `// GENERATED by scripts/build-icons.mjs from the previous frontend's icon sprite. Do not edit.\n\n` +
    `export interface Imported {\n  viewBox: string;\n  body: string;\n}\n\n` +
    `/** Full-colour icons: coins, resources, victory points, shields and the ten progress tokens. */\n` +
    `export const IMPORTED: Readonly<Partial<Record<string, Imported>>> = {\n${entries}\n};\n`,
);
console.log(`${String(icons.length)} icons`);
